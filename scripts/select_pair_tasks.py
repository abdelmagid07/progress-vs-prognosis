#!/usr/bin/env python
"""Pick the tasks that can become within-task pairs, and write the instance list.

A pair needs one resolved and one unresolved trajectory of the SAME task. Every task the main
run resolved already owns its resolved arm, so turning one into a pair costs only the
generation of a failing arm. This selects those tasks and freezes the list before any compute
is booked, so the input is reviewable rather than recomputed inside a notebook where a silent
change would go unnoticed.

Outputs, both under data/:
  pair_instances.txt   one SWE-bench instance id per line, the format
                       run_mini_swe_batch.sh turns into a --filter regex
  pair_manifest.json   provenance: source table, resolve rate, the selected ids, and the
                       expected-attempts floor

Nothing here touches a GPU.

Reproduce: python scripts/select_pair_tasks.py
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "data"


def _outcomes(path: Path) -> pd.DataFrame:
    """One row per trajectory: task_id, trajectory_id, seed, outcome."""
    cols = ["task_id", "trajectory_id", "seed", "outcome"]
    df = pd.read_parquet(path, columns=cols).drop_duplicates()
    dupes = df.trajectory_id.duplicated().sum()
    if dupes:
        raise SystemExit(f"{path.name}: {dupes} trajectory_ids carry conflicting outcomes")
    return df


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--full", type=Path, default=OUT_DIR / "projections_full.parquet",
                    help="the main run")
    ap.add_argument("--exclude", type=Path, default=None,
                    help="optional projections table of tasks that already have both arms")
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR)
    args = ap.parse_args()

    full = _outcomes(args.full)
    already = set(_outcomes(args.exclude).task_id.unique()) if args.exclude else set()

    resolved = full.loc[full.outcome == 1, "task_id"]
    todo = sorted(set(resolved) - already)

    # A pair needs both arms. Every id in `todo` already has its resolved arm, so only the
    # failing arm is missing -- assert that rather than trusting the set algebra.
    assert not (set(todo) & already), "task is both paired and unpaired"
    missing_resolved = [t for t in todo if not (full.task_id.eq(t) & full.outcome.eq(1)).any()]
    assert not missing_resolved, f"no resolved arm on record for {missing_resolved[:5]}"

    n_full = full.trajectory_id.nunique()
    resolve_rate = full.outcome.mean()

    # Expected generations. This is a floor, not an estimate: it uses the run-wide resolve
    # rate, but the selected tasks are exactly the ones the model has already solved once, so
    # their conditional resolve rate is higher and some need several attempts. Budget above
    # this number and cap attempts per task in the runner.
    p_fail_floor = 1 - resolve_rate
    expected_floor = len(todo) / p_fail_floor if p_fail_floor else float("inf")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    txt = args.out_dir / "pair_instances.txt"
    header = [
        "# Tasks needing a failing arm to become a within-task pair.",
        "# Generated by scripts/select_pair_tasks.py -- do not hand-edit.",
        f"# {len(todo)} tasks | source: {args.full.name}",
        "# Each already has a RESOLVED arm; generation must produce a FAILING one.",
        "",
    ]
    txt.write_text("\n".join(header + todo) + "\n", encoding="utf-8")

    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "source_full": args.full.name,
        "n_trajectories_full_run": int(n_full),
        "run_resolve_rate": float(resolve_rate),
        "n_resolved_tasks": int(resolved.nunique()),
        "n_needing_failing_arm": len(todo),
        "target_n_pairs": len(already) + len(todo),
        "expected_generations_floor": round(expected_floor, 1),
        "needs_failing_arm": todo,
    }
    js = args.out_dir / "pair_manifest.json"
    js.write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    print(f"main run           : {n_full} trajectories, resolve rate {resolve_rate:.3f}")
    print(f"resolved tasks     : {resolved.nunique()}")
    print(f"need failing arm   : {len(todo)}")
    print(f"target pair count  : {len(already) + len(todo)}")
    print(f"generations (floor): ~{expected_floor:.0f}  "
          f"-- a floor only; these tasks resolve more often than the run average")
    print(f"\nwrote {txt}")
    print(f"wrote {js}")


if __name__ == "__main__":
    main()
