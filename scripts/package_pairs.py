#!/usr/bin/env python
"""Assemble both arms of every pair into one normalized directory, then zip it for projection.

Runs after generate_pair_arms.py. Two jobs:

1. Ingest the failing arms generated by each round into normalized trajectory JSON.
2. Pull each task's RESOLVED arm out of the main run's normalized directory and place it
   alongside, under the paired naming convention (``<task>.json`` resolved,
   ``<task>__failed.json`` unresolved).

Both arms are re-projected even though the resolved ones were projected once already. The main
run's table carries neither ``proj_final`` nor ``n_gen_tokens`` and keeps no per-token
activations, and the paired analyses need both. Re-projecting both arms under the same
pipeline is what makes the two sides of a pair comparable rather than differently measured.

Output: data/normalized_pairs/ and data/normalized_pairs.zip, which stage 3 projects into
data/projections_pairs50.parquet and data/pairs50_meanpool.npz.

Reproduce: python scripts/package_pairs.py
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def ingest_rounds(run_root: Path, staging: Path) -> None:
    """Normalize every round's raw trajectories into one staging directory."""
    rounds = sorted(d for d in run_root.glob("round*") if d.is_dir())
    if not rounds:
        raise SystemExit(f"no round*/ directories under {run_root}; run generate_pair_arms.py first")
    staging.mkdir(parents=True, exist_ok=True)
    for rd in rounds:
        print(f"  ingesting {rd.name} ...", flush=True)
        subprocess.check_call(
            [sys.executable, "-m", "prognosis.agent.ingest_batch",
             "--traj-dir", str(rd), "--format", "mini-swe-agent",
             "--output-dir", str(staging)],
            cwd=str(ROOT),
        )


def load_norm(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def write_norm(rec: dict, path: Path) -> None:
    path.write_text(json.dumps(rec), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-root", type=Path,
                    default=ROOT / "data" / "trajectories" / "pairs")
    ap.add_argument("--main-run-normalized", type=Path, required=True,
                    help="normalized directory of the 499-trajectory main run (holds the "
                         "resolved arms)")
    ap.add_argument("--out-dir", type=Path,
                    default=ROOT / "data" / "normalized_pairs")
    ap.add_argument("--zip-path", type=Path, default=ROOT / "data" / "normalized_pairs.zip")
    ap.add_argument("--skip-ingest", action="store_true",
                    help="reuse an existing staging dir instead of re-running ingest")
    args = ap.parse_args()

    state_path = args.run_root / "pair_state.json"
    if not state_path.exists():
        raise SystemExit(f"missing {state_path}; run generate_pair_arms.py first")
    state = json.loads(state_path.read_text(encoding="utf-8"))
    want = sorted(t for t, r in state["tasks"].items() if r["failing_seed"] is not None)
    if not want:
        raise SystemExit("no failing arms recorded yet -- nothing to package")

    staging = args.run_root / "_normalized_staging"
    if not args.skip_ingest:
        ingest_rounds(args.run_root, staging)

    out = args.out_dir
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    # --- failing arms -------------------------------------------------------------------
    by_task: dict[str, list[Path]] = {}
    for p in staging.glob("*.json"):
        if p.name == "ingest_manifest.json":
            continue
        rec = load_norm(p)
        by_task.setdefault(rec["task_id"], []).append(p)

    placed_fail, problems = [], []
    for task in want:
        cands = [p for p in by_task.get(task, []) if load_norm(p).get("outcome") == 0]
        if not cands:
            problems.append(f"{task}: state says a failing arm exists, but none is normalized")
            continue
        # Multiple rounds can leave more than one failure; take the seed the state recorded so
        # the shipped arm is the one the run log describes.
        seed = state["tasks"][task]["failing_seed"]
        chosen = next((p for p in cands if load_norm(p).get("seed") == seed), cands[0])
        rec = load_norm(chosen)
        rec["trajectory_id"] = f"{task}__failed"
        write_norm(rec, out / f"{task}__failed.json")
        placed_fail.append(task)

    # --- resolved arms ------------------------------------------------------------------
    main_norm = args.main_run_normalized
    if not main_norm.is_dir():
        raise SystemExit(f"--main-run-normalized {main_norm} is not a directory")
    main_index: dict[str, Path] = {}
    for p in main_norm.glob("*.json"):
        if p.name == "ingest_manifest.json":
            continue
        rec = load_norm(p)
        if rec.get("outcome") == 1:
            main_index[rec["task_id"]] = p

    placed_ok = []
    for task in placed_fail:
        src = main_index.get(task)
        if src is None:
            problems.append(f"{task}: no resolved arm found in {main_norm}")
            (out / f"{task}__failed.json").unlink(missing_ok=True)
            continue
        rec = load_norm(src)
        rec["trajectory_id"] = task
        write_norm(rec, out / f"{task}.json")
        placed_ok.append(task)

    # --- validate -----------------------------------------------------------------------
    pairs = []
    for task in sorted(placed_ok):
        a, b = out / f"{task}.json", out / f"{task}__failed.json"
        ra, rb = load_norm(a), load_norm(b)
        if (ra["outcome"], rb["outcome"]) != (1, 0):
            problems.append(f"{task}: outcomes are {ra['outcome']}/{rb['outcome']}, expected 1/0")
            continue
        if ra["task_id"] != rb["task_id"]:
            problems.append(f"{task}: task_id mismatch between arms")
            continue
        pairs.append(task)

    n_files = len(list(out.glob("*.json")))
    if n_files != 2 * len(pairs):
        problems.append(f"{n_files} files for {len(pairs)} pairs -- expected {2*len(pairs)}")

    print(f"\nnew pairs packaged : {len(pairs)}")
    print(f"trajectories to project: {2 * len(pairs)}")
    print(f"total pairs packaged   : {len(pairs)}")
    if problems:
        print("\nPROBLEMS (fix before projecting):")
        for p in problems:
            print("  -", p)

    manifest = {
        "n_pairs": len(pairs),
        "n_trajectories": 2 * len(pairs),
        "tasks": pairs,
        "main_run_normalized": str(main_norm),
        "note": "both arms shipped: the main run's parquet lacks proj_final/n_gen_tokens, so "
                "resolved arms are re-projected under the paired pipeline for comparability",
    }
    (out / "pair_package.json").write_text(json.dumps(manifest, indent=2),
                                                     encoding="utf-8")

    with zipfile.ZipFile(args.zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(out.glob("*.json")):
            z.write(p, arcname=f"{out.name}/{p.name}")
    size_mb = args.zip_path.stat().st_size / 1e6
    print(f"\nwrote {args.zip_path}  ({size_mb:.1f} MB)")
    print("Project that zip (stage 3), then run scripts/normalize_pair_layers.py")


if __name__ == "__main__":
    main()
